import 'dotenv/config';
import { createUser } from '../server/db';
import { getProfile } from '../server/investors';
import { pool } from '../server/database';
import fs from 'node:fs';
const tag=Date.now().toString().slice(-7), password='ReferralDemo123!';
const parent=await createUser({username:'referrer_demo_'+tag,password,name:'Demo Referrer',role:'investor'});
const p=(await getProfile(parent.id))!;
const child=await createUser({username:'referred_demo_'+tag,password,name:'Demo Referred Investor',role:'investor',referredByCode:p.referralCode});
const api=async(method:string,path:string,body?:object,token?:string)=>{const r=await fetch('http://localhost:8787'+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});const data=await r.json() as any;if(!r.ok)throw Error(JSON.stringify(data));return data;};
const admin=await api('POST','/api/auth/login',{username:'Admin',password:'Admin'});
const {plan}=await api('POST','/api/admin/plans',{name:'Referral Demo 5% '+tag,minInvestmentUsd:100,maxInvestmentUsd:100000,status:'Active',directReferralPercent:5},admin.token);
await api('PUT','/api/admin/investors/'+child.id,{plan:plan.name,totalInvestmentUsd:10000,kycStatus:'Verified',accountStatus:'Active'},admin.token);
const login=await api('POST','/api/auth/login',{username:parent.username,password});
const stats=await api('GET','/api/investor/referrals',undefined,login.token);
const profile=await api('GET','/api/investor/profile',undefined,login.token);
const fixture={parentUsername:parent.username,childUsername:child.username,password,referralCode:p.referralCode,planName:plan.name,stats,profile};
fs.writeFileSync('docs/referral-live-demo.json',JSON.stringify(fixture,null,2));
console.log(JSON.stringify({parentUsername:parent.username,childUsername:child.username,password,referralCode:p.referralCode,planName:plan.name,stats}));
await pool.end();
